// build.js: builds the blog from the sources in blog/posts/.
//
// For each blog/posts/<slug>.tex (files whose names start with "_" are
// skipped, so use that for templates and drafts):
//   blog/<slug>.html   the post page, rendered by pandoc with blog/template.html
// And from all posts together:
//   feed.xml           RSS feed; the site's post lists and email sign-ups read it
//   sitemap.xml
//
// Each post needs \title{...}, \date{YYYY-MM-DD} and an abstract
// environment, which becomes its description.
//
// Usage: node build.js   (the pre-commit hook in .githooks/ runs this for you)
// Needs pandoc on your PATH (or set PANDOC=/path/to/pandoc).

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

// -------- CONFIG --------
const SITE_URL = "https://nathancantafio.com";
const SITE_TITLE = "Nathan Cantafio";
const SITE_DESCRIPTION =
  "Writing by Nathan Cantafio on probability, statistics, and mathematics.";
const STATIC_PAGES = ["/", "/all-posts.html", "/notes.html", "/cv/"];
// ------------------------

const ROOT = __dirname;
const POSTS_DIR = path.join(ROOT, "blog", "posts");
const OUT_DIR = path.join(ROOT, "blog");
const TEMPLATE = path.join(OUT_DIR, "template.html");
const MARKER = "<!-- Generated by build.js"; // marks pages this script owns
const RESERVED = new Set(["post", "template"]); // existing files in blog/

function fail(msg) {
  console.error(`build.js: ${msg}`);
  process.exit(1);
}

function pandoc(args) {
  try {
    return execFileSync(process.env.PANDOC || "pandoc", args, {
      cwd: POSTS_DIR, // so relative paths like a .bib file resolve from blog/posts/
      encoding: "utf8",
      stdio: ["ignore", "pipe", "inherit"],
    });
  } catch (err) {
    if (err.code === "ENOENT") fail("pandoc not found. Install it with: brew install pandoc");
    fail(`pandoc failed on ${args[0]}`);
  }
}

const escapeXml = (s) =>
  String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

// Read a post's metadata (title, date, abstract) as plain text.
const metaTemplate = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "blog-")), "meta.tpl");
fs.writeFileSync(metaTemplate, "$meta-json$\n");

function readPost(file) {
  const slug = path.basename(file, ".tex");
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug))
    fail(`${file}: use lowercase letters, digits and dashes in post file names`);
  if (RESERVED.has(slug)) fail(`${file}: "${slug}" is a reserved name`);

  const meta = JSON.parse(
    pandoc([file, "-f", "latex", "-t", "plain", "--wrap=none", "--quiet", "--template", metaTemplate])
  );
  const title = (meta.title || "").trim();
  const date = (meta.date || "").trim();
  const description = (meta.abstract || "").trim().replace(/\s+/g, " ");

  if (!title) fail(`${file}: missing title`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) fail(`${file}: date must look like 2026-05-04, got "${date}"`);
  if (!description) fail(`${file}: missing description (add an abstract environment)`);

  return { file, slug, title, date, description, bibliography: meta.bibliography };
}

function renderPost(post) {
  const args = [
    post.file,
    "-f", "latex",
    "-t", "html5",
    "--mathjax",
    "--wrap=none",
    "--template", TEMPLATE,
    "--lua-filter", path.join(OUT_DIR, "filters.lua"),
    // \section becomes <h3> and \subsection <h4>, under the post title's <h2>.
    "--shift-heading-level-by=2",
    "-V", `slug=${post.slug}`,
    "-V", `source=${post.file}`,
    "-V", `metadesc=${escapeXml(post.description)}`,
    "-o", path.join(OUT_DIR, `${post.slug}.html`),
  ];
  if (post.bibliography) args.push("--citeproc");
  pandoc(args);
}

const postUrl = (post) => `${SITE_URL}/blog/${post.slug}.html`;
// Noon UTC, so the day is the same in nearly every time zone.
const rssDate = (date) => new Date(`${date}T12:00:00Z`).toUTCString();

function writeFeed(posts) {
  const items = posts
    .map(
      (p) => `
    <item>
      <title>${escapeXml(p.title)}</title>
      <link>${postUrl(p)}</link>
      <guid isPermaLink="true">${postUrl(p)}</guid>
      <pubDate>${rssDate(p.date)}</pubDate>
      <description>${escapeXml(p.description)}</description>
    </item>`
    )
    .join("");

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by build.js from blog/posts/. Do not edit by hand. -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${escapeXml(SITE_TITLE)}</title>
    <link>${SITE_URL}/</link>
    <description>${escapeXml(SITE_DESCRIPTION)}</description>
    <language>en</language>
    <atom:link href="${SITE_URL}/feed.xml" rel="self" type="application/rss+xml" />${items}
  </channel>
</rss>
`;
  fs.writeFileSync(path.join(ROOT, "feed.xml"), xml);
}

function writeSitemap(posts) {
  const url = (loc, lastmod) =>
    `  <url>\n    <loc>${SITE_URL}${loc}</loc>\n` +
    (lastmod ? `    <lastmod>${lastmod}</lastmod>\n` : "") +
    `  </url>\n`;

  const xml =
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    STATIC_PAGES.map((p) => url(p)).join("") +
    posts.map((p) => url(`/blog/${p.slug}.html`, p.date)).join("") +
    `</urlset>\n`;
  fs.writeFileSync(path.join(ROOT, "sitemap.xml"), xml);
}

// Remove pages built from posts that no longer exist (renamed or deleted).
function removeStalePages(posts) {
  const current = new Set(posts.map((p) => `${p.slug}.html`));
  for (const name of fs.readdirSync(OUT_DIR)) {
    const full = path.join(OUT_DIR, name);
    if (!name.endsWith(".html") || full === TEMPLATE || current.has(name)) continue;
    if (fs.readFileSync(full, "utf8").includes(MARKER)) {
      fs.unlinkSync(full);
      console.log(`removed blog/${name} (its source is gone)`);
    }
  }
}

// -------- main --------
const files = fs
  .readdirSync(POSTS_DIR)
  .filter((f) => !f.startsWith("_") && f.endsWith(".tex"))
  .sort();

const posts = files.map(readPost);
posts.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));

posts.forEach(renderPost);
removeStalePages(posts);
writeFeed(posts);
writeSitemap(posts);

console.log(`build.js: ${posts.length} posts -> blog/*.html, feed.xml, sitemap.xml`);
