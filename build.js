// build.js: builds the site's generated parts.
//
// 1. Blog posts. For each blog/posts/<slug>.tex (files whose names start
//    with "_" are skipped, so use that for templates and drafts):
//      blog/<slug>.html   the post page, rendered by pandoc with blog/template.html
//    And from all posts together:
//      feed.xml           RSS feed; email sign-ups read it
//      sitemap.xml
//
//    Each post needs \title{...}, \date{YYYY-MM-DD} and an abstract
//    environment, which becomes its description.
//
// 2. Shared page parts. Every page (index.html, notes.html, the post pages,
//    ...) has regions marked like this:
//
//      <!-- build:header -->
//      ...
//      <!-- /build:header -->
//
//    This script rewrites whatever is between the two markers, so don't edit
//    there by hand: edit the source instead and run the build.
//
//      build:head            fonts, favicon and link-preview tags (set below)
//      build:header          header.html, with the current page's link marked
//      build:sidebar         sidebar.html
//      build:posts           every post, newest first (all-posts.html)
//      build:recent-posts    the three newest posts (inside sidebar.html)
//      build:recent-writing  the three newest posts with dates (for index.html)
//
//    To make a new page, copy an existing one: the markers come with it.
//
// Usage: node build.js   (the pre-commit hook in .githooks/ runs this for you)
// Needs pandoc on your PATH (or set PANDOC=/path/to/pandoc).

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

// -------- CONFIG --------
const SITE_URL = "https://nathancantafio.com";
const SITE_TITLE = "Nathan Cantafio";
const SITE_DESCRIPTION =
  "Writing by Nathan Cantafio on probability, statistics, and mathematics.";
const STATIC_PAGES = ["/", "/all-posts.html", "/notes.html", "/cv/"];
const FONTS_URL =
  "https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,300;0,600;1,300;1,600&family=DM+Sans:wght@300;400;500&family=STIX+Two+Text:ital,wght@0,400;0,600;1,400;1,600&display=swap";
// Image shown when a link to the site is shared (Slack, iMessage, LinkedIn...).
const PREVIEW_IMAGE = "/favicon/og-image.png";
// Browsers hold on to favicons for a long time. Bump this when the icon changes.
const FAVICON_VERSION = "2";
const RECENT_COUNT = 3;
// ------------------------

const ROOT = __dirname;
const POSTS_DIR = path.join(ROOT, "blog", "posts");
const OUT_DIR = path.join(ROOT, "blog");
const TEMPLATE = path.join(OUT_DIR, "template.html");
const HEADER = path.join(ROOT, "header.html");
const SIDEBAR = path.join(ROOT, "sidebar.html");
const MARKER = "<!-- Generated by build.js"; // marks pages this script owns
const RESERVED = new Set(["post", "template"]); // existing files in blog/

function fail(msg) {
  console.error(`build.js: ${msg}`);
  process.exit(1);
}

function pandoc(args) {
  try {
    return execFileSync(process.env.PANDOC || "pandoc", args, {
      cwd: POSTS_DIR, // so relative paths like a .bib file resolve from blog/posts/
      encoding: "utf8",
      stdio: ["ignore", "pipe", "inherit"],
    });
  } catch (err) {
    if (err.code === "ENOENT") fail("pandoc not found. Install it with: brew install pandoc");
    fail(`pandoc failed on ${args[0]}`);
  }
}

const escapeXml = (s) =>
  String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

const unescapeXml = (s) =>
  String(s)
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&");

// "2026-05-04" -> "May 4, 2026". Noon UTC, so the day is the same in nearly every time zone.
const asDate = (date) => new Date(`${date}T12:00:00Z`);
const longDate = (date) =>
  asDate(date).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" });
const monthYear = (date) =>
  asDate(date).toLocaleDateString("en-US", { year: "numeric", month: "short", timeZone: "UTC" });

// ======== Blog posts ========

// Read a post's metadata (title, date, abstract) as plain text.
const metaTemplate = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "blog-")), "meta.tpl");
fs.writeFileSync(metaTemplate, "$meta-json$\n");

function readPost(file) {
  const slug = path.basename(file, ".tex");
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug))
    fail(`${file}: use lowercase letters, digits and dashes in post file names`);
  if (RESERVED.has(slug)) fail(`${file}: "${slug}" is a reserved name`);

  const meta = JSON.parse(
    pandoc([file, "-f", "latex", "-t", "plain", "--wrap=none", "--quiet", "--template", metaTemplate])
  );
  const title = (meta.title || "").trim();
  const date = (meta.date || "").trim();
  const description = (meta.abstract || "").trim().replace(/\s+/g, " ");

  if (!title) fail(`${file}: missing title`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) fail(`${file}: date must look like 2026-05-04, got "${date}"`);
  if (!description) fail(`${file}: missing description (add an abstract environment)`);

  return { file, slug, title, date, description, bibliography: meta.bibliography };
}

function renderPost(post) {
  const args = [
    post.file,
    "-f", "latex",
    "-t", "html5",
    "--math-method=mathjax", // needs pandoc 3.11 or newer
    "--wrap=none",
    "--template", TEMPLATE,
    "--lua-filter", path.join(OUT_DIR, "filters.lua"),
    // \section becomes <h3> and \subsection <h4>, under the post title.
    "--shift-heading-level-by=2",
    "-V", `slug=${post.slug}`,
    "-V", `source=${post.file}`,
    "-V", `metadesc=${escapeXml(post.description)}`,
    "-V", `datelong=${longDate(post.date)}`,
    "-o", path.join(OUT_DIR, `${post.slug}.html`),
  ];
  if (post.bibliography) args.push("--citeproc");
  pandoc(args);
}

const postPath = (post) => `/blog/${post.slug}.html`;
const postUrl = (post) => SITE_URL + postPath(post);
const rssDate = (date) => asDate(date).toUTCString();

function writeFeed(posts) {
  const items = posts
    .map(
      (p) => `
    <item>
      <title>${escapeXml(p.title)}</title>
      <link>${postUrl(p)}</link>
      <guid isPermaLink="true">${postUrl(p)}</guid>
      <pubDate>${rssDate(p.date)}</pubDate>
      <description>${escapeXml(p.description)}</description>
    </item>`
    )
    .join("");

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by build.js from blog/posts/. Do not edit by hand. -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${escapeXml(SITE_TITLE)}</title>
    <link>${SITE_URL}/</link>
    <description>${escapeXml(SITE_DESCRIPTION)}</description>
    <language>en</language>
    <atom:link href="${SITE_URL}/feed.xml" rel="self" type="application/rss+xml" />${items}
  </channel>
</rss>
`;
  fs.writeFileSync(path.join(ROOT, "feed.xml"), xml);
}

function writeSitemap(posts) {
  const url = (loc, lastmod) =>
    `  <url>\n    <loc>${SITE_URL}${loc}</loc>\n` +
    (lastmod ? `    <lastmod>${lastmod}</lastmod>\n` : "") +
    `  </url>\n`;

  const xml =
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    STATIC_PAGES.map((p) => url(p)).join("") +
    posts.map((p) => url(postPath(p), p.date)).join("") +
    `</urlset>\n`;
  fs.writeFileSync(path.join(ROOT, "sitemap.xml"), xml);
}

// Remove pages built from posts that no longer exist (renamed or deleted).
function removeStalePages(posts) {
  const current = new Set(posts.map((p) => `${p.slug}.html`));
  for (const name of fs.readdirSync(OUT_DIR)) {
    const full = path.join(OUT_DIR, name);
    if (!name.endsWith(".html") || full === TEMPLATE || current.has(name)) continue;
    if (fs.readFileSync(full, "utf8").includes(MARKER)) {
      fs.unlinkSync(full);
      console.log(`removed blog/${name} (its source is gone)`);
    }
  }
}

// ======== Shared page parts ========

// What goes inside each <!-- build:NAME --> region. `page` describes the page
// being stamped; `posts` is every post, newest first.
const REGIONS = {
  head(page) {
    const v = `?v=${FAVICON_VERSION}`;
    const lines = [
      `<link rel="preconnect" href="https://fonts.googleapis.com">`,
      `<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>`,
      `<link rel="stylesheet" href="${escapeXml(FONTS_URL)}">`,
      `<link rel="icon" href="/favicon/favicon.ico${v}" sizes="32x32">`,
      `<link rel="icon" type="image/svg+xml" href="/favicon/favicon.svg${v}">`,
      `<link rel="icon" type="image/png" href="/favicon/favicon-96x96.png${v}" sizes="96x96">`,
      `<link rel="apple-touch-icon" sizes="180x180" href="/favicon/apple-touch-icon.png${v}">`,
      `<meta name="apple-mobile-web-app-title" content="${escapeXml(SITE_TITLE)}">`,
      `<link rel="manifest" href="/favicon/site.webmanifest">`,
      `<meta name="theme-color" content="#2C1810">`,
    ];
    // Link-preview tags. Pages marked noindex (404, subscribed) don't get them.
    if (!page.noindex) {
      lines.push(
        `<meta property="og:site_name" content="${escapeXml(SITE_TITLE)}">`,
        `<meta property="og:type" content="${page.isPost ? "article" : "website"}">`,
        `<meta property="og:title" content="${escapeXml(page.title)}">`
      );
      if (page.description)
        lines.push(`<meta property="og:description" content="${escapeXml(page.description)}">`);
      lines.push(
        `<meta property="og:url" content="${escapeXml(page.url)}">`,
        `<meta property="og:image" content="${SITE_URL}${PREVIEW_IMAGE}">`,
        `<meta property="og:image:alt" content="${escapeXml(SITE_TITLE)}">`,
        `<meta name="twitter:card" content="summary">`
      );
    }
    return lines.join("\n");
  },

  // header.html, with the link to the current page marked active. A link is
  // active when it points at this page; posts light up the data-page="blog" link.
  header(page) {
    return fs.readFileSync(HEADER, "utf8").replace(/<a\b([^>]*\bdata-page="[^"]*"[^>]*)>/g, (tag, attrs) => {
      const href = (attrs.match(/\bhref="([^"]*)"/) || [])[1] || "";
      const name = (attrs.match(/\bdata-page="([^"]*)"/) || [])[1];
      const active = href.replace(/\/index\.html$/, "/") === page.path || (page.isPost && name === "blog");
      return active ? `<a${attrs} class="active" aria-current="page">` : tag;
    });
  },

  sidebar() {
    return fs.readFileSync(SIDEBAR, "utf8");
  },

  posts(page, posts) {
    return posts
      .map(
        (p) =>
          `<li class="entry">\n` +
          `  <time class="entry-meta" datetime="${p.date}">${longDate(p.date)}</time>\n` +
          `  <a class="entry-title" href="${postPath(p)}">${escapeXml(p.title)}</a>\n` +
          `  <p class="entry-desc">${escapeXml(p.description)}</p>\n` +
          `</li>`
      )
      .join("\n");
  },

  "recent-posts"(page, posts) {
    return posts
      .slice(0, RECENT_COUNT)
      .map((p) => `<li><a href="${postPath(p)}">${escapeXml(p.title)}</a></li>`)
      .join("\n");
  },

  "recent-writing"(page, posts) {
    return posts
      .slice(0, RECENT_COUNT)
      .map(
        (p) =>
          `<li><a href="${postPath(p)}">${escapeXml(p.title)}</a> ` +
          `<span class="post-date">${monthYear(p.date)}</span></li>`
      )
      .join("\n");
  },
};

const REGION_RE = /([ \t]*)<!-- build:([a-z-]+) -->[\s\S]*?<!-- \/build:\2 -->/g;

// Fill every region in `html`. Regions can nest: the sidebar holds the recent posts.
function stamp(html, page, posts) {
  return html.replace(REGION_RE, (match, indent, name) => {
    if (!REGIONS[name]) fail(`${page.file}: unknown region "build:${name}"`);
    const inner = stamp(REGIONS[name](page, posts).trim(), page, posts)
      .split("\n")
      .map((line) => (line ? indent + line : line))
      .join("\n");
    return `${indent}<!-- build:${name} -->\n${inner}\n${indent}<!-- /build:${name} -->`;
  });
}

// What the regions need to know about a page, read from the page itself.
function describePage(file, html) {
  const rel = path.relative(ROOT, file).split(path.sep).join("/");
  const pagePath = "/" + rel.replace(/(^|\/)index\.html$/, "$1");
  const title = unescapeXml((html.match(/<title>([\s\S]*?)<\/title>/) || [])[1] || SITE_TITLE)
    .trim()
    .replace(/\s+[—–-]\s+Nathan Cantafio$/, "");
  const description = unescapeXml(
    (html.match(/<meta\s+name="description"\s+content="([^"]*)"/) || [])[1] || ""
  );
  const canonical = (html.match(/<link\s+rel="canonical"\s+href="([^"]*)"/) || [])[1];
  return {
    file: rel,
    path: pagePath,
    url: canonical || SITE_URL + pagePath,
    title,
    description,
    noindex: /<meta\s+name="robots"\s+content="[^"]*noindex/.test(html),
    isPost: html.includes(MARKER),
  };
}

// Every .html file in the site, apart from the sources the regions are made from.
function findPages(dir = ROOT) {
  const skip = new Set([TEMPLATE, HEADER, SIDEBAR]);
  const pages = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!entry.name.startsWith(".") && entry.name !== "node_modules") pages.push(...findPages(full));
    } else if (entry.name.endsWith(".html") && !skip.has(full)) {
      pages.push(full);
    }
  }
  return pages.sort();
}

function stampPages(posts) {
  let count = 0;
  for (const file of findPages()) {
    const html = fs.readFileSync(file, "utf8");
    const page = describePage(file, html);
    // style.css no longer loads the fonts itself: build:head does.
    if (html.includes('href="/style.css"') && !html.includes("<!-- build:head -->"))
      console.warn(`build.js: warning: ${page.file} uses style.css but has no build:head region, so it won't load the fonts`);
    if (!html.includes("<!-- build:")) continue;
    const stamped = stamp(html, page, posts);
    if (stamped !== html) fs.writeFileSync(file, stamped);
    count++;
  }
  return count;
}

// -------- main --------
const files = fs
  .readdirSync(POSTS_DIR)
  .filter((f) => !f.startsWith("_") && f.endsWith(".tex"))
  .sort();

const posts = files.map(readPost);
posts.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));

posts.forEach(renderPost);
removeStalePages(posts);
writeFeed(posts);
writeSitemap(posts);
const stamped = stampPages(posts);

console.log(`build.js: ${posts.length} posts -> blog/*.html, feed.xml, sitemap.xml; shared parts stamped into ${stamped} pages`);
